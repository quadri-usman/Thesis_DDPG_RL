"""pwm.py

Exact readable translation of the three-phase PWM/gate logic generated by
Simulink Coder in SubsystemGFM.cpp for the MATLAB benchmark.

Generated structure
-------------------
* Base simulation step: 10 us (from parameters.py)
* Carrier frequency: 5000 Hz
* Carrier period: 200 us
* Carrier lookup breakpoints: [0, 0.5, 1.0]
* Carrier lookup table:        [0, 2.0, 0]
* Generated offset produces a triangle in [-1, +1]
* Three phase references are reconstructed from alpha-beta as

      ma = alpha
      mb = -0.5*alpha + sqrt(3)/2*beta
      mc = -0.5*alpha - sqrt(3)/2*beta

* Upper switch gate: phase_reference >= carrier
* Lower switch gate: logical complement of upper gate

The generated C++ does NOT clip the controller modulation command before this
comparison.  Therefore this benchmark module intentionally applies no
modulation saturation.
"""

from dataclasses import dataclass
import math
import numpy as np

from parameters import PARAMS, BenchmarkParameters


@dataclass(frozen=True)
class PWMInput:
    """Controller command entering the generated three-phase PWM stage."""

    modulation_alpha: float
    modulation_beta: float


@dataclass(frozen=True)
class PWMOutput:
    """Generated PWM quantities for one benchmark sample."""

    carrier: float

    ma: float
    mb: float
    mc: float

    # Gate ordering matches generated DataTypeConversion[0:6]:
    # [A_upper, A_lower, B_upper, B_lower, C_upper, C_lower]
    gates: np.ndarray

    @property
    def gate_a_upper(self) -> int:
        return int(self.gates[0])

    @property
    def gate_a_lower(self) -> int:
        return int(self.gates[1])

    @property
    def gate_b_upper(self) -> int:
        return int(self.gates[2])

    @property
    def gate_b_lower(self) -> int:
        return int(self.gates[3])

    @property
    def gate_c_upper(self) -> int:
        return int(self.gates[4])

    @property
    def gate_c_lower(self) -> int:
        return int(self.gates[5])


class GeneratedPWM:
    """5-kHz natural-sampling PWM translated from generated C++ code."""

    def __init__(
        self,
        params: BenchmarkParameters = PARAMS,
        carrier_frequency: float = 5000.0,
    ):
        self.params = params
        self.carrier_frequency = float(carrier_frequency)
        self.carrier_period = 1.0 / self.carrier_frequency

    @staticmethod
    def _triangle_from_normalized_phase(phase: float) -> float:
        """Generated lookup-table carrier for phase in [0, 1).

        Simulink generated a lookup table with
            bp    = [0, 0.5, 1]
            table = [0, 2, 0]
        followed by an offset of -1.

        Hence the final carrier is
            -1 -> +1 -> -1.
        """

        phase = phase % 1.0

        if phase <= 0.5:
            lookup = 4.0 * phase
        else:
            lookup = 4.0 * (1.0 - phase)

        return lookup - 1.0

    def carrier(self, time: float) -> float:
        """Return the generated triangular carrier at simulation time ``time``."""

        # Equivalent to generated expression:
        # 5000 * rem(time, 0.0002)
        normalized_phase = (
            self.carrier_frequency
            * math.fmod(float(time), self.carrier_period)
        )

        # Protect against tiny negative fmod values if a caller supplies a
        # negative time. Normal benchmark simulation starts at t >= 0.
        normalized_phase %= 1.0

        return self._triangle_from_normalized_phase(normalized_phase)

    @staticmethod
    def alpha_beta_to_abc(alpha: float, beta: float) -> tuple[float, float, float]:
        """Generated inverse alpha-beta mapping immediately before PWM."""

        half = 0.5
        sqrt3_over_2 = math.sqrt(3.0) / 2.0

        ma = alpha
        mb = -half * alpha + sqrt3_over_2 * beta
        mc = -half * alpha - sqrt3_over_2 * beta

        return float(ma), float(mb), float(mc)

    def evaluate(self, time: float, inputs: PWMInput) -> PWMOutput:
        """Evaluate carrier, phase references, and six gate commands."""

        carrier = self.carrier(time)

        ma, mb, mc = self.alpha_beta_to_abc(
            inputs.modulation_alpha,
            inputs.modulation_beta,
        )

        upper = np.asarray(
            [
                ma >= carrier,
                mb >= carrier,
                mc >= carrier,
            ],
            dtype=np.int8,
        )

        lower = 1 - upper

        gates = np.asarray(
            [
                upper[0], lower[0],
                upper[1], lower[1],
                upper[2], lower[2],
            ],
            dtype=np.int8,
        )

        return PWMOutput(
            carrier=float(carrier),
            ma=ma,
            mb=mb,
            mc=mc,
            gates=gates,
        )

    def step(self, time: float, controller_output) -> PWMOutput:
        """Convenience interface accepting ``controller.ControllerOutput``."""

        return self.evaluate(
            time,
            PWMInput(
                modulation_alpha=float(controller_output.modulation_alpha),
                modulation_beta=float(controller_output.modulation_beta),
            ),
        )


def pwm_step(
    time: float,
    modulation_alpha: float,
    modulation_beta: float,
    params: BenchmarkParameters = PARAMS,
) -> PWMOutput:
    """Stateless convenience wrapper for one PWM evaluation."""

    pwm = GeneratedPWM(params=params)
    return pwm.evaluate(
        time,
        PWMInput(
            modulation_alpha=modulation_alpha,
            modulation_beta=modulation_beta,
        ),
    )


if __name__ == "__main__":
    pwm = GeneratedPWM()

    # Carrier sanity check at quarter-cycle points of the 200-us period.
    print("Generated PWM sanity check")
    for t in [0.0, 50e-6, 100e-6, 150e-6, 200e-6]:
        print(f"t={t:9.6f} s  carrier={pwm.carrier(t): .6f}")

    out = pwm.evaluate(
        0.0,
        PWMInput(
            modulation_alpha=0.2,
            modulation_beta=-0.1,
        ),
    )

    print("phase refs:", out.ma, out.mb, out.mc)
    print("gates     :", out.gates)
