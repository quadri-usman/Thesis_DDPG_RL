"""measurements.py

Measurement layer for the full MATLAB/Simulink generated-code benchmark.

The mappings in this file are taken from ``SubsystemGFM.cpp`` generated by
Simulink Coder.  The generated Specialized Power Systems block exposes a
19-element vector named ``StateSpace_o1``.  The generated controller uses:

    StateSpace_o1[6:9]    -> B3 three-phase voltage (Vabc_B3)
    StateSpace_o1[12:15]  -> B3 three-phase current (Iabc_B3)
    StateSpace_o1[15]     -> battery/DC-side current
    StateSpace_o1[16:19]  -> B1 inverter/filter current (Iabc_B1)

Indices 0:6 are internal ideal-switch outputs used by the generated SPS switch
solver.  Indices 9:12 are not assigned a physical name here because the
controller code inspected so far does not establish their meaning unambiguously.
They remain available as ``aux_abc`` for later mapping.

The abc->dq transform reproduces the generated Clarke gain (2/3) followed by
the selected Simulink ``abc to dq0`` alignment (90 degrees behind phase A).
The same GFM electrical angle is used for B3 voltage, B3 current and B1 current,
as in the generated controller.
"""

from dataclasses import dataclass
import numpy as np

from plant import PlantOutput


# Exact StateSpace_o1 mappings established from SubsystemGFM.cpp.
IDX_SWITCH = slice(0, 6)
IDX_VABC_B3 = slice(6, 9)
IDX_AUX_ABC = slice(9, 12)
IDX_IABC_B3 = slice(12, 15)
IDX_BATTERY_CURRENT = 15
IDX_IABC_B1 = slice(16, 19)


@dataclass(frozen=True)
class DQ0:
    d: float
    q: float
    zero: float


@dataclass(frozen=True)
class BenchmarkMeasurements:
    """Physical signals consumed by the generated GFM controller."""

    # Raw generated abc signals.
    vabc_b3: np.ndarray
    iabc_b3: np.ndarray
    iabc_b1: np.ndarray

    # Unmapped StateSpace_o1[9:12], retained for later identification.
    aux_abc: np.ndarray

    # DC-side/battery current: StateSpace_o1[15].
    battery_current: float

    # Controller-frame dq quantities.
    vod: float
    voq: float
    v0: float

    iod: float
    ioq: float
    i0_b3: float

    ifd: float
    ifq: float
    i0_b1: float

    # Power calculated from the same B3 dq voltage/current used by MATLAB.
    P: float
    Q: float
    S: float

    # Raw generated switch-port outputs for diagnostics.
    switch_outputs: np.ndarray


def clarke_abc_to_alpha_beta_zero(abc) -> np.ndarray:
    """Generated amplitude-invariant Clarke transform.

    This is the matrix visible in generated code as Gain3 followed by Gain1=2/3:

        alpha = 2/3 * (a - b/2 - c/2)
        beta  = 2/3 * (sqrt(3)/2*b - sqrt(3)/2*c)
        zero  = 1/3 * (a + b + c)
    """

    a, b, c = np.asarray(abc, dtype=np.float64).reshape(3)

    alpha = (2.0 / 3.0) * (a - 0.5 * b - 0.5 * c)
    beta = (2.0 / 3.0) * ((np.sqrt(3.0) / 2.0) * (b - c))
    zero = (a + b + c) / 3.0

    return np.array([alpha, beta, zero], dtype=np.float64)


def alpha_beta_to_dq(alpha: float, beta: float, theta: float) -> tuple[float, float]:
    """Park rotation used for the benchmark controller frame.

    With the Simulink block configured as ``90 degrees behind phase A axis``,
    a balanced positive-sequence vector aligned with the controller frame has
    d equal to its amplitude and q approximately zero.
    """

    c = np.cos(theta)
    s = np.sin(theta)

    # Exact generated Simulink branch for the configured
    # "90 degrees behind phase A axis" alignment.
    # GFM_py.cpp::Subsystempi2delay computes:
    #   d = alpha*sin(theta) - beta*cos(theta)
    #   q = alpha*cos(theta) + beta*sin(theta)
    # This is also the exact inverse of the generated controller dq->alpha-beta:
    #   alpha = d*sin(theta) + q*cos(theta)
    #   beta  = -d*cos(theta) + q*sin(theta)
    d = alpha * s - beta * c
    q = alpha * c + beta * s

    return float(d), float(q)


def abc_to_dq0(abc, theta: float) -> DQ0:
    """Convert one generated three-phase signal into controller-frame dq0."""

    alpha, beta, zero = clarke_abc_to_alpha_beta_zero(abc)
    d, q = alpha_beta_to_dq(alpha, beta, theta)
    return DQ0(d=d, q=q, zero=float(zero))


def measurement_step(plant_output: PlantOutput, theta: float) -> BenchmarkMeasurements:
    """Decode ``StateSpace_o1`` and reproduce MATLAB controller measurements.

    Parameters
    ----------
    plant_output:
        Raw 19-output generated SPS plant output.
    theta:
        GFM/controller electrical angle used by MATLAB's abc->dq0 blocks.
    """

    y = np.asarray(plant_output.y, dtype=np.float64).reshape(19)

    vabc_b3 = y[IDX_VABC_B3].copy()
    aux_abc = y[IDX_AUX_ABC].copy()
    iabc_b3 = y[IDX_IABC_B3].copy()
    iabc_b1 = y[IDX_IABC_B1].copy()

    voltage = abc_to_dq0(vabc_b3, theta)
    current_b3 = abc_to_dq0(iabc_b3, theta)
    current_b1 = abc_to_dq0(iabc_b1, theta)

    # Exact P/Q algebra used in the Simulink controller diagram.
    P = 1.5 * (
        voltage.d * current_b3.d
        + voltage.q * current_b3.q
    )

    Q = 1.5 * (
        voltage.q * current_b3.d
        - voltage.d * current_b3.q
    )

    S = float(np.hypot(P, Q))

    return BenchmarkMeasurements(
        vabc_b3=vabc_b3,
        iabc_b3=iabc_b3,
        iabc_b1=iabc_b1,
        aux_abc=aux_abc,
        battery_current=float(y[IDX_BATTERY_CURRENT]),
        vod=voltage.d,
        voq=voltage.q,
        v0=voltage.zero,
        iod=current_b3.d,
        ioq=current_b3.q,
        i0_b3=current_b3.zero,
        ifd=current_b1.d,
        ifq=current_b1.q,
        i0_b1=current_b1.zero,
        P=float(P),
        Q=float(Q),
        S=S,
        switch_outputs=y[IDX_SWITCH].copy(),
    )


